# Regenerates esp32/food_spoilage_monitor/web_page.h from web/index.html
# and esp32/food_spoilage_monitor/favicon_svg.h from web/favicon.svg.
# Run from the project root after editing those sources:
#     powershell -File tools\embed_page.ps1   (Windows)
#     python tools/embed_page.py              (macOS / Linux / Windows)

function ConvertTo-RawLiteral {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][string]$Symbol,
        [Parameter(Mandatory)][string]$Source,
        [Parameter(Mandatory)][string]$Out
    )
    # Read as UTF-8 (if no BOM) and keep every byte, including newline style.
    # NB: Get-Content -Raw would decode with the OEM/ANSI codepage on Windows
    # PowerShell 5.1 and corrupt non-ASCII characters - use .NET instead.
    $content = [System.IO.File]::ReadAllText($Path)
    if ($content -match '\)rawliteral"') {
        Write-Error "$Path contains the raw-string terminator )rawliteral`" - please rename it."
        exit 1
    }
    $header = @"
// AUTO-GENERATED by tools/embed_page.ps1 - do not edit by hand.
// Source: $Source
#pragma once
#include <Arduino.h>

const char $Symbol[] PROGMEM =
R"rawliteral(
"@
    $text = $header + $content + ')rawliteral";'
    # UTF-8 without BOM - identical to the Python generator.
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Out, $text, $utf8)
    Write-Host ("Wrote {0} ({1} KB)" -f $Out, [math]::Round((Get-Item $Out).Length / 1024, 1))
}

ConvertTo-RawLiteral `
    -Path  (Join-Path $PSScriptRoot '..\web\index.html') `
    -Symbol 'MAIN_page' `
    -Source 'web/index.html' `
    -Out   (Join-Path $PSScriptRoot '..\esp32\food_spoilage_monitor\web_page.h')

ConvertTo-RawLiteral `
    -Path  (Join-Path $PSScriptRoot '..\web\favicon.svg') `
    -Symbol 'FAVICON_svg' `
    -Source 'web/favicon.svg' `
    -Out   (Join-Path $PSScriptRoot '..\esp32\food_spoilage_monitor\favicon_svg.h')
