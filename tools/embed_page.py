#!/usr/bin/env python3
"""Regenerates the ESP32 PROGMEM headers from the web sources:

  web/index.html  -> esp32/food_spoilage_monitor/web_page.h   (MAIN_page)
  web/favicon.svg -> esp32/food_spoilage_monitor/favicon_svg.h (FAVICON_svg)

Run from anywhere:  python tools/embed_page.py
(Windows users can use tools/embed_page.ps1 instead.)
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, "esp32", "food_spoilage_monitor")


def embed(src_rel, symbol, dst_name):
    src = os.path.join(ROOT, src_rel)
    dst = os.path.join(TARGET, dst_name)
    with open(src, "r", encoding="utf-8") as f:
        content = f.read()
    assert ')rawliteral"' not in content, (
        f'{src_rel} contains the raw-string terminator )rawliteral" - rename it.'
    )
    header = (
        "// AUTO-GENERATED by tools/embed_page.py - do not edit by hand.\n"
        f"// Source: {src_rel}\n"
        "#pragma once\n"
        "#include <Arduino.h>\n\n"
        f"const char {symbol}[] PROGMEM =\nR\"rawliteral("
    )
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + content + ')rawliteral";')
    print(f"Wrote {dst} ({os.path.getsize(dst) / 1024:.1f} KB)")


embed("web/index.html", "MAIN_page", "web_page.h")
embed("web/favicon.svg", "FAVICON_svg", "favicon_svg.h")
